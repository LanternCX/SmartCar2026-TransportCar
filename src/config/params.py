"""配置管理模块

@file src/config/params.py
@brief 搬运车控制系统的全局参数配置

@details 集中存放搬运车控制的所有可调参数, 包括控制周期、PWM 限制、运动学参数、PID 增益、陀螺仪滤波、位置控制等
"""

# ===== 时序与周期 =====
# 主控制循环周期, 单位毫秒
TICK_MS = 5
# 可靠短包发送前后的固定延时, 单位毫秒
RELIABLE_PACKET_SEND_DELAY_MS = 1
# 待确认可靠短包重发间隔, 单位毫秒
RELIABLE_RESEND_INTERVAL_MS = 20

# ===== 主车搜索参数 =====
# 主车搜索下发给视觉 hook 的配置编号
MASTER_SEARCH_HOOK_CONFIG_ID = 1

# ===== 电机与 PWM =====
# PWM 占空比上限, 范围 0 ~ 10000, 对应 0% ~ 100%
MAX_DUTY = 10000

# ===== 命令与速度限制 =====
# 命令输入限幅, 用于限制来自上游的速度指令幅度
V_CMD_MAX = 1e3
# 轮速目标限幅, 单位为 Pulses/tick, 防止给速度环的目标值过大
TARGET_SPEED_MAX = 30.0

# ===== 位置控制参数 =====
# 位置控制最大速度, 单位 m/s, 在 P 控制中作为饱和限幅
POS_MAX_SPEED = 0.05
# 位置控制比例系数, 单位 Speed (m/s) / Error (m), 决定偏差如何转换为速度指令
POS_KP = 2.0
# 位置锁定容差, 单位米, 位置偏差小于此值时认为已到达目标
POS_TOLERANCE = 0.05
# 角度锁定容差, 单位度, 角度偏差小于此值时认为已到达目标
ANGLE_TOLERANCE = 5.0

# ===== 轮子配置 =====
# 启用的轮子集合, 用于调试时选择性激活特定轮子(默认启用全部)
ACTIVE_WHEELS = ("m", "l", "r")

# ===== 陀螺仪参数 =====
# 陀螺仪低通滤波系数(一阶 IIR 滤波器 alpha 参数), 范围 0 ~ 1
# 值越大滤波强度越弱, 值越小则响应越迟缓
GYRO_LPF_ALPHA = 0.2
# 陀螺仪比例因子, 单位 LSB / (deg/s), 用于原始数值到角速度的转换
GYRO_SCALE = 16.384
# 角速度 Z 轴在 IMU 返回数组中的索引位置(0-5 分别为 ax, ay, az, gx, gy, gz)
GYRO_AXIS_Z = 5

# ===== 偏航角 PID 参数 =====
# 偏航角位置环 P 增益, 单位为 ω / rad, 控制偏航误差的反馈强度
YAW_KP = 0.16
# 偏航角位置环 I 增益, 用于消除稳态偏差
YAW_KI = 0.1
# 偏航角位置环 D 增益, 用于阻尼控制
YAW_KD = 0.008
# 积分项饱和限幅, 防止积分超调
YAW_I_MAX = 100.0
# 自动回正最大角速度, 对应轮速分量, 决定回正时的最大回转速度
AUTO_OMEGA_MAX = 15.0
# 保持模式速度阈值, 当目标轮速小于此值时判定为保持模式
HOLD_SPEED_EPS = 0.01

# ===== 文件路径 =====
# 系统辨识参数的保存路径, 用于存储轮子的增益和时间常数
IDENT_RESULTS_FILE = "/flash/ident_params.txt"
# 陀螺仪零飘偏移的保存路径, 用于存储静止时的陀螺仪平均值
GYRO_OFFSET_FILE = "/flash/gyro_offset.txt"

# ===== 速度环参数表 =====
# 三轮速度环 PID 参数映射, 键为轮子标识符(m/l/r), 值为 (P, D, P2) 元组
# P: 增量式 PID 的比例增益
# D: 增量式 PID 的微分增益(基于速度差)
# P2: 前馈补偿的比例项
PID_MAP = {
    "m": (100, 500, 1),
    "l": (100, 500, 1),
    "r": (100, 500, 1),
}
